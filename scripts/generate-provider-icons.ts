/**
 * Emits the standalone provider marks served at `/providers/<provider>.svg`.
 *
 * The React components in `src/components/provider-icons.tsx` stay the single
 * source of truth: this script renders each one to markup, strips the bits that
 * only make sense inside the app (baked-in pixel size, aria-hidden, per-render
 * clip ids) and writes the result into `public/`, which Vite then copies into
 * `dist/client` for the production server.
 *
 *   bun scripts/generate-provider-icons.ts           # write files
 *   bun scripts/generate-provider-icons.ts --check   # fail if files are stale
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { PROVIDER_ICONS } from "../src/components/provider-icons";
import type { ProviderId } from "../src/lib/types";

const OUT_DIR = join(dirname(fileURLToPath(import.meta.url)), "..", "public", "providers");

const BANNER =
  "<!-- Generated by scripts/generate-provider-icons.ts - do not edit by hand. -->";

/** Renders like the app does, then trims everything only the app needs. */
function toStandaloneSvg(provider: ProviderId): string {
  const markup = renderToStaticMarkup(
    createElement(PROVIDER_ICONS[provider], { size: 24 }),
  );
  // Only the root tag carries a pixel size; keep every other width/height
  // attribute (e.g. Composio's clip rect) exactly as authored.
  const rootEnd = markup.indexOf(">") + 1;
  const root = markup
    .slice(0, rootEnd)
    .replace(/\s+(width|height)="\d+"/gu, "")
    // Decorative by definition; the referencing element carries the label.
    .replace(/\s+aria-hidden="true"/gu, "");

  return (
    `${BANNER}\n` +
    (root +
      markup
        .slice(rootEnd)
        // React's useId is stable per render but not across renders; clip ids
        // in a committed file should be readable and deterministic.
        .replace(/id="[^"]*"/gu, `id="${provider}-clip"`)
        .replace(/url\(#[^)]*\)/gu, `url(#${provider}-clip)`)
        .replace(/></gu, ">\n<")) +
    "\n"
  );
}

const check = process.argv.includes("--check");
mkdirSync(OUT_DIR, { recursive: true });

const stale: string[] = [];
let written = 0;

for (const provider of Object.keys(PROVIDER_ICONS) as ProviderId[]) {
  const file = join(OUT_DIR, `${provider}.svg`);
  const next = toStandaloneSvg(provider);

  let current: string | null = null;
  try {
    current = readFileSync(file, "utf8");
  } catch {
    current = null;
  }

  if (current === next) continue;
  if (check) {
    stale.push(`${provider}.svg`);
    continue;
  }

  writeFileSync(file, next);
  written += 1;
  console.log(`wrote public/providers/${provider}.svg`);
}

if (check) {
  if (stale.length > 0) {
    console.error(
      `Provider icons are out of date: ${stale.join(", ")}\n` +
        "Run `bun run icons` and commit the result.",
    );
    process.exit(1);
  }
  console.log(`Provider icons are up to date (${Object.keys(PROVIDER_ICONS).length}).`);
} else {
  console.log(written === 0 ? "Provider icons already up to date." : `Done (${written} updated).`);
}
